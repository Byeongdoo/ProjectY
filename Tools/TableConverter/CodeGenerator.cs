using System.Text;

namespace TableConverter;

/// <summary>JSON과 같은 모양의 C# 데이터 클래스·테이블·TableManager를 생성한다. 클라·서버 공통 파일.</summary>
internal static class CodeGenerator
{
    public sealed record Entry(SheetTable Table, List<Column> KeyCols);

    public static string Generate(List<Entry> entries)
    {
        var sb = new StringBuilder();
        void L(string s = "") => sb.Append(s).Append('\n');

        L("// <auto-generated>");
        L("// TableConverter가 Table/MasterTable.xlsx에서 생성한 파일입니다. 직접 수정하지 마세요.");
        L("// 수정이 필요하면 xlsx(또는 Tools/TableConverter)를 고치고 다시 변환하세요.");
        L("// </auto-generated>");
        L("#nullable disable");
        L("using System;");
        L("using System.Collections.Generic;");
        L();
        L("namespace Table");
        L("{");
        L("    /// <summary>JSON 파일을 읽어 역직렬화한다. 서버는 Newtonsoft, 클라는 Resources + JsonUtility로 구현한다.</summary>");
        L("    public interface ITableReader");
        L("    {");
        L("        TFile Read<TFile>(string fileName) where TFile : class;");
        L("    }");
        L();
        L("    /// <summary>키로 조회하는 읽기 전용 테이블. 키가 중복되면 생성 시 예외.</summary>");
        L("    public class RowTable<TKey, TRow>");
        L("    {");
        L("        readonly Dictionary<TKey, TRow> _dict = new Dictionary<TKey, TRow>();");
        L("        readonly List<TRow> _rows;");
        L();
        L("        public string Sheet { get; }");
        L("        public IReadOnlyList<TRow> Rows => _rows;");
        L("        public int Count => _rows.Count;");
        L();
        L("        protected RowTable(string sheet, IEnumerable<TRow> rows, Func<TRow, TKey> keyOf)");
        L("        {");
        L("            Sheet = sheet;");
        L("            _rows = new List<TRow>(rows);");
        L("            foreach (TRow row in _rows)");
        L("            {");
        L("                TKey key = keyOf(row);");
        L("                if (!_dict.TryAdd(key, row))");
        L("                    throw new InvalidOperationException($\"{sheet}: 키 {key} 중복\");");
        L("            }");
        L("        }");
        L();
        L("        public bool TryGet(TKey key, out TRow row) => _dict.TryGetValue(key, out row);");
        L();
        L("        public TRow Get(TKey key)");
        L("        {");
        L("            if (_dict.TryGetValue(key, out TRow row)) return row;");
        L("            throw new KeyNotFoundException($\"{Sheet}: 키 {key}가 없음\");");
        L("        }");
        L("    }");

        foreach (Entry e in entries)
            EmitSheet(sb, e);

        EmitManager(sb, entries);
        L("}");
        return sb.ToString();
    }

    static void EmitSheet(StringBuilder sb, Entry e)
    {
        SheetTable t = e.Table;
        string pascal = Pascal(t.Name);
        void L(string s = "") => sb.Append(s).Append('\n');

        L();
        L($"    // ===== {t.Name} =====");
        L("    [Serializable]");
        L($"    public class {pascal}Row");
        L("    {");
        foreach (Column c in t.Columns)
        {
            if (c.Label.Length > 0)
                L($"        /// <summary>{Escape(c.Label)}</summary>");
            string type = CsType(c);
            string init = c.IsList ? $" = new {type}()" : c.Type == ColType.String ? " = \"\"" : "";
            L($"        public {type} {Id(c.Key)}{init};");
        }
        L("    }");
        L();
        L("    [Serializable]");
        L($"    public class {pascal}File");
        L("    {");
        L($"        public List<{pascal}Row> rows = new List<{pascal}Row>();");
        L("    }");
        L();

        string keyType, keyOf;
        if (e.KeyCols.Count == 1)
        {
            keyType = CsType(e.KeyCols[0]);
            keyOf = $"r.{Id(e.KeyCols[0].Key)}";
        }
        else
        {
            keyType = "(" + string.Join(", ", e.KeyCols.Select(k => $"{CsType(k)} {Id(k.Key)}")) + ")";
            keyOf = "(" + string.Join(", ", e.KeyCols.Select(k => $"r.{Id(k.Key)}")) + ")";
        }

        L($"    public sealed class {pascal}Table : RowTable<{keyType}, {pascal}Row>");
        L("    {");
        L($"        public {pascal}Table(IEnumerable<{pascal}Row> rows) : base(\"{t.Name}\", rows, r => {keyOf}) {{ }}");
        L("    }");
    }

    static void EmitManager(StringBuilder sb, List<Entry> entries)
    {
        void L(string s = "") => sb.Append(s).Append('\n');

        L();
        L("    /// <summary>모든 마스터 테이블에 접근하는 진입점. 시작 시 LoadAll을 한 번 호출한다.</summary>");
        L("    public static partial class TableManager");
        L("    {");
        foreach (Entry e in entries)
            L($"        public static {Pascal(e.Table.Name)}Table {Pascal(e.Table.Name)} {{ get; private set; }}");
        L();
        L("        /// <summary>하나라도 실패하면 어느 파일인지 담은 예외를 던진다. 호출 쪽은 즉시 종료해야 한다.</summary>");
        L("        public static void LoadAll(ITableReader reader)");
        L("        {");
        foreach (Entry e in entries)
        {
            string p = Pascal(e.Table.Name);
            L($"            {p} = Load<{p}File, {p}Table>(reader, \"{p}\", f => new {p}Table(f.rows));");
        }
        L("        }");
        L();
        L("        static TTable Load<TFile, TTable>(ITableReader reader, string fileName, Func<TFile, TTable> build) where TFile : class");
        L("        {");
        L("            try");
        L("            {");
        L("                TFile file = reader.Read<TFile>(fileName);");
        L("                if (file == null) throw new InvalidOperationException(\"내용이 비어 있거나 형식이 맞지 않음\");");
        L("                return build(file);");
        L("            }");
        L("            catch (Exception ex)");
        L("            {");
        L("                throw new InvalidOperationException($\"테이블 로딩 실패: {fileName}.json — {ex.Message}\", ex);");
        L("            }");
        L("        }");
        L("    }");
    }

    static string CsType(Column c)
    {
        string t = c.Type switch
        {
            ColType.Int => c.Wide ? "long" : "int",
            ColType.Float => "float",
            _ => "string",
        };
        return c.IsList ? $"List<{t}>" : t;
    }

    // C# 예약어와 겹치는 컬럼명은 @접두사로 쓴다 (예: clues.case → @case). JSON 키는 그대로.
    static readonly HashSet<string> Keywords = new()
    {
        "abstract","as","base","bool","break","byte","case","catch","char","checked","class","const","continue",
        "decimal","default","delegate","do","double","else","enum","event","explicit","extern","false","finally",
        "fixed","float","for","foreach","goto","if","implicit","in","int","interface","internal","is","lock","long",
        "namespace","new","null","object","operator","out","override","params","private","protected","public",
        "readonly","ref","return","sbyte","sealed","short","sizeof","stackalloc","static","string","struct","switch",
        "this","throw","true","try","typeof","uint","ulong","unchecked","unsafe","ushort","using","virtual","void",
        "volatile","while",
    };

    static string Id(string name) => Keywords.Contains(name) ? "@" + name : name;

    public static string Pascal(string sheet) => char.ToUpperInvariant(sheet[0]) + sheet[1..];

    static string Escape(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\r", " ").Replace("\n", " ");
}
